# so parallel work never edits the same table. Keys must stay unique across all files.
_here = os.path.dirname(os.path.abspath(__file__))
_more = os.path.join(_here, "strings")
if os.path.isdir(_more):
    for _name in sorted(os.listdir(_more)):
        if _name.endswith(".py"):
            _ns = {}
            exec(open(os.path.join(_more, _name), encoding="utf-8").read(), _ns)
            S.extend(_ns.get("S", []))
            for _k, _v in _ns.get("P", {}).items():
                assert _k not in P, _k
                P[_k] = _v

def esc(s):
    s = escape(s).replace("'", "\\'").replace('"', '\\"')
    if s.startswith("@") or s.startswith("?"): s = "\\" + s
    # aapt trims leading and trailing spaces unless the value is quoted (the «، » separator needs its space).
    if s != s.strip(): s = '"' + s + '"'
    return s

def write(path, idx):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    out = ['<?xml version="1.0" encoding="utf-8"?>', '<!-- Generated from one table: keep Arabic and English in step. -->', '<resources>']
    keys = set()
    for row in S:
        assert row[0] not in keys, row[0]; keys.add(row[0])
        text = row[idx]
        attr = ''
        out.append(f'    <string name="{row[0]}"{attr}>{esc(text)}</string>')
    for name, forms in P.items():
        out.append(f'    <plurals name="{name}">')
        for q, t in forms[idx - 1].items():
            out.append(f'        <item quantity="{q}">{esc(t)}</item>')
        out.append('    </plurals>')
    out.append('</resources>')
    open(path, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")

res = sys.argv[1]
write(os.path.join(res, "values", "strings.xml"), 1)
write(os.path.join(res, "values-en", "strings.xml"), 2)
print(len(S), "strings")
