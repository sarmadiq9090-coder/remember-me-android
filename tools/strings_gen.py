def esc(s):
    s = escape(s).replace("'", "\\'").replace('"', '\\"')
    if s.startswith("@") or s.startswith("?"): s = "\\" + s
    return s

def write(path, idx):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    out = ['<?xml version="1.0" encoding="utf-8"?>', '<!-- Generated from one table: keep Arabic and English in step. -->', '<resources>']
    keys = set()
    for row in S:
        assert row[0] not in keys, row[0]; keys.add(row[0])
        text = row[idx]
        attr = ''
        out.append(f'    <string name="{row[0]}"{attr}>{esc(text)}</string>')
    for name, forms in P.items():
        out.append(f'    <plurals name="{name}">')
        for q, t in forms[idx - 1].items():
            out.append(f'        <item quantity="{q}">{esc(t)}</item>')
        out.append('    </plurals>')
    out.append('</resources>')
    open(path, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")

