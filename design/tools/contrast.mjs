// WCAG 2.2 contrast check of every colour pair the Remember Me design uses (light + dark).
// Reads design/tools/palette.json (from palette.mjs) and writes design/tools/contrast-report.md.
// Run: node design\tools\contrast.mjs   (exit code 1 if any required pair fails)
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
const here = path.dirname(fileURLToPath(import.meta.url));
const P = JSON.parse(fs.readFileSync(path.join(here, 'palette.json'), 'utf8'));
function lum(hex) {
  const c = [1, 3, 5].map(i => parseInt(hex.slice(i, i + 2), 16) / 255)
    .map(v => (v <= 0.04045 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4)));
  return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
}
const ratio = (a, b) => { const x = lum(a), y = lum(b); return (Math.max(x, y) + 0.05) / (Math.min(x, y) + 0.05); };
// Fixed brand colours (same in both themes): the icon tile and its bell, used only in the brand mark.
const BRAND = { tile: '#123B2A', bell: '#C5B3FF', lime: '#B9F34A', white: '#FFFFFF' };
// [foreground, background, minimum, use]; 4.5 = text (1.4.3), 3 = UI boundary / large text (1.4.11), 0 = decorative
const pairs = [
  ['onSurface', 'surface', 4.5, 'body text, section headers on the page'],
  ['onSurfaceVariant', 'surface', 4.5, 'supporting text, metadata, empty-state body'],
  ['onSurface', 'surfaceContainer', 4.5, 'reminder title, time (hero) on a row'],
  ['onSurfaceVariant', 'surfaceContainer', 4.5, 'row metadata (repeat, day) and settings supporting text'],
  ['error', 'surfaceContainer', 4.5, 'overdue time and «متأخر …» text on a row (with an icon too)'],
  ['error', 'surface', 4.5, 'overdue time on the reminder screen'],
  ['primary', 'surface', 4.5, 'text buttons, section header «اليوم», links'],
  ['primary', 'surfaceContainer', 4.5, 'text button inside a row or card'],
  ['onPrimary', 'primary', 4.5, 'FAB label, filled button «تم» / «حفظ»'],
  ['onPrimaryContainer', 'primaryContainer', 4.5, 'selected weekday, «جاهز» status chip'],
  ['onSecondaryContainer', 'secondaryContainer', 4.5, 'tonal button, selected segment, backup banner'],
  ['onTertiaryContainer', 'tertiaryContainer', 4.5, 'priority tag «مهم» / «متوسط», bell disc'],
  ['onErrorContainer', 'errorContainer', 4.5, 'warning banner «قد لا تصل التذكيرات…», «مطلوب»'],
  ['onSurface', 'surfaceContainerHigh', 4.5, 'search field text, dialog text'],
  ['onSurfaceVariant', 'surfaceContainerHigh', 4.5, 'search placeholder'],
  ['onSurface', 'surfaceContainerLow', 4.5, 'bottom action bar, sheet text'],
  ['inverseOnSurface', 'inverseSurface', 4.5, 'snackbar text'],
  ['inversePrimary', 'inverseSurface', 4.5, 'snackbar action «تراجع»'],
  ['outline', 'surface', 3, 'UI: outlined button, text field, segment outline (1.4.11)'],
  ['outline', 'surfaceContainer', 3, 'UI: the Done circle on a row, chip outline (1.4.11)'],
  ['primary', 'surface', 3, 'UI: FAB container, switch track on (1.4.11)'],
  ['primary', 'surfaceContainer', 3, 'UI: checked Done circle, selected weekday circle (1.4.11)'],
  ['outline', 'surfaceContainerHighest', 3, 'UI: switch track off border (1.4.11)'],
  ['onSurfaceVariant', 'surfaceContainer', 3, 'UI: row icons (repeat, flag, chevron) (1.4.11)'],
  ['outlineVariant', 'surface', 0, 'decorative divider, group gap (exempt)'],
];
let report = `# Contrast report\n\nGenerated by \`design/tools/contrast.mjs\` from \`palette.json\` (seed ${P.seed}, tertiary ${P.tertiarySeed}).\nWCAG 2.2: text 4.5:1 (1.4.3), UI boundaries and icons 3:1 (1.4.11).\n`;
let fails = 0;
for (const theme of ['light', 'dark']) {
  const s = P[theme];
  report += `\n## ${theme === 'light' ? 'Light' : 'Dark'}\n\n| Foreground | Background | Use | Ratio | Needs | Result |\n|---|---|---|---|---|---|\n`;
  for (const [f, b, min, use] of pairs) {
    const r = ratio(s[f], s[b]);
    const ok = min === 0 || r >= min;
    if (!ok) fails++;
    report += `| ${f} \`${s[f]}\` | ${b} \`${s[b]}\` | ${use} | ${r.toFixed(2)}:1 | ${min ? min + ':1' : 'n/a'} | ${min === 0 ? 'decorative' : ok ? 'PASS' : '**FAIL**'} |\n`;
  }
}
// Fixed colours
const fixed = [
  ['bell', 'tile', 3, 'brand mark: lavender bell on the deep-green tile (graphic, 1.4.11)'],
  ['lime', 'tile', 3, 'brand mark: lime corner on the tile (graphic)'],
  ['white', 'tile', 4.5, 'widget header text if drawn on the tile colour'],
];
report += `\n## Fixed brand colours (both themes)\n\n| Foreground | Background | Use | Ratio | Needs | Result |\n|---|---|---|---|---|---|\n`;
for (const [f, b, min, use] of fixed) {
  const r = ratio(BRAND[f], BRAND[b]); const ok = r >= min; if (!ok) fails++;
  report += `| ${f} \`${BRAND[f]}\` | ${b} \`${BRAND[b]}\` | ${use} | ${r.toFixed(2)}:1 | ${min}:1 | ${ok ? 'PASS' : '**FAIL**'} |\n`;
}
// Mockup system notification surfaces are the phone's own; the app sets only the accent (setColor).
const nl = ratio(P.light.primary, '#FFFFFF'), nd = ratio(P.dark.primary, '#202124');
report += `\nNotification accent (\`setColor\` = light primary ${P.light.primary}) on a white shade: ${nl.toFixed(2)}:1; dark primary ${P.dark.primary} on a typical dark shade #202124: ${nd.toFixed(2)}:1 (both ≥ 4.5).\n`;
report += `\n**Result: ${fails === 0 ? 'every required pair passes' : fails + ' failing pair(s)'}.**\n`;
fs.writeFileSync(path.join(here, 'contrast-report.md'), report);
console.log(report);
process.exit(fails ? 1 : 0);
