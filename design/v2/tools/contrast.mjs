// WCAG 2.2 contrast check of every colour pair the Remember Me 1.0.0 design (v2) uses, light + dark.
// The palette is unchanged from v1: it reads design/tools/palette.json (made by design/tools/palette.mjs).
// Writes design/v2/tools/contrast-report.md. Run: node design\v2\tools\contrast.mjs  (exit 1 on any failure)
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
const here = path.dirname(fileURLToPath(import.meta.url));
const P = JSON.parse(fs.readFileSync(path.resolve(here, '..', '..', 'tools', 'palette.json'), 'utf8'));
function lum(hex) {
  const c = [1, 3, 5].map(i => parseInt(hex.slice(i, i + 2), 16) / 255)
    .map(v => (v <= 0.04045 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4)));
  return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
}
const ratio = (a, b) => { const x = lum(a), y = lum(b); return (Math.max(x, y) + 0.05) / (Math.min(x, y) + 0.05); };
// [foreground, background, minimum, use]; 4.5 = text (1.4.3), 3 = UI boundary / icon (1.4.11), 0 = decorative
